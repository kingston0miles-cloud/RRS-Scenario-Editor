#ifndef     RSE_FORMATION_H
#define     RSE_FORMATION_H

#include    "scenario/scenario.h"

#include    <QString>
#include    <QStringList>

namespace rse
{

//------------------------------------------------------------------------------
// Формирование поезда: локомотив по графику приходит к стоящим вагонам, сцепляется,
// и дальше едет уже новый поезд со своим графиком (продолжение).
//
// Как это устроено в симуляторе: при сцепке остаётся поезд с меньшим индексом
// (порядок setTrain), он сохраняет своё имя. Новое имя и график включаются
// командой renameTrain (она заново читает timetable/<имя>.xml), а развернуть
// поезд головой в обратную сторону - командой reverseTrain
//------------------------------------------------------------------------------
struct FormationPlan
{
    bool ok = false;
    QString error;

    int locoIndex = -1;
    int wagonsIndex = -1;

    /// Когда локомотив прибывает на конечную точку своего графика, с
    int arrivalTime = 0;

    /// Раньше этого времени продолжение отправляться не должно: прибытие + задержка
    int readyTime = 0;

    /// Локомотив в конечной точке графика
    PlacedTrain locoAtEnd;

    /// Поезд-продолжение: положение головы (бывший хвост локомотива, голова смотрит
    /// обратно), состав локомотив + вагоны, длина, масса. График не заполняется
    PlacedTrain formed;

    /// Локомотив встал вплотную к вагонам, они автоматически сцепятся
    bool couples = false;

    QStringList warnings;
};

/// Рассчитать продолжение cont (оно уже может стоять в сценарии)
FormationPlan planFormation(const Route &route, const Scenario &scenario,
                            const PlacedTrain &cont);

/// Порядок setTrain: у локомотива индекс меньше, чем у вагонов, иначе после сцепки
/// выживет и сохранит имя поезд с вагонами. Возвращает порядок индексов поездов
/// сценария для экспорта; продолжения в него не входят
QVector<int> exportOrder(const Scenario &scenario);

} // namespace rse

#endif // RSE_FORMATION_H
